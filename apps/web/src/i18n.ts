export function t(lang: string, key: string, vars?: Record<string, string | number>) {
  let s = (dict[lang] && dict[lang][key]) || dict.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return s;
}

export function dirFor(lang: string) {
  return lang === "he" || lang === "ar" ? "rtl" : "ltr";
}

/** Desk UI language from localStorage; updates when AppShell dispatches docflow:lang. */
export function useDeskLang() {
  const [lang, setLang] = useState(() => localStorage.getItem("docflow.lang") || "en");
  useEffect(() => {
    const sync = () => setLang(localStorage.getItem("docflow.lang") || "en");
    window.addEventListener("docflow:lang", sync);
    return () => window.removeEventListener("docflow:lang", sync);
  }, []);
  return lang;
}
